// Keep transitive JNI libraries on the same architectures as Flutter and the
// native assets. Otherwise a single-ABI APK can advertise an incomplete ABI.
val packagedAbis = (project.findProperty("target-platform") as? String
    ?: "android-arm,android-arm64,android-x64").split(",").map { target ->
    when (target.trim()) {
        "android-arm" -> "armeabi-v7a"
        "android-arm64" -> "arm64-v8a"
        "android-x64" -> "x86_64"
        else -> error("Unsupported Android target platform: $target")
    }
}

